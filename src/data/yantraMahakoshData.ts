export function getYantrasForKundali(lagnaSign?: string, moonSign?: string, doshas?: string[]): SacredYantraItem[] {
  const normalizedLagna = (lagnaSign || '').split('(')[0].trim();
  const normalizedMoon = (moonSign || '').split('(')[0].trim();
  const joinedDoshas = (doshas || []).join(' ');

  const matched: SacredYantraItem[] = [];

  // 1. Dosh Based Priority
  if (joinedDoshas.includes('मांगलिक') || joinedDoshas.includes('मंगल')) {
    const mangal = SACRED_YANTRAS_COLLECTION.find((y) => y.id === 'mangal_yantra');
    if (mangal) matched.push(mangal);
  }
  if (joinedDoshas.includes('कालसर्प')) {
    const kalsarp = SACRED_YANTRAS_COLLECTION.find((y) => y.id === 'kalsarp_yantra');
    if (kalsarp) matched.push(kalsarp);
  }
  if (joinedDoshas.includes('साढ़ेसाती') || joinedDoshas.includes('ढैय्या') || joinedDoshas.includes('शनि')) {
    const shani = SACRED_YANTRAS_COLLECTION.find((y) => y.id === 'shani_yantra');
    if (shani) matched.push(shani);
  }

  // 2. Lagna / Rashi based
  for (const y of SACRED_YANTRAS_COLLECTION) {
    if (matched.some((m) => m.id === y.id)) continue;

    const matchesLagna = y.associatedLagnas.some((l) => normalizedLagna.includes(l));
    const matchesSign = y.associatedSigns.some((s) => normalizedMoon.includes(s));

    if (matchesLagna || matchesSign) {
      matched.push(y);
    }
    if (matched.length >= 3) break;
  }

  // Fallback defaults if none matched
  if (matched.length === 0) {
    const defaultSri = SACRED_YANTRAS_COLLECTION.find((y) => y.id === 'sri_yantra')!;
    const defaultSurya = SACRED_YANTRAS_COLLECTION.find((y) => y.id === 'surya_yantra')!;
    matched.push(defaultSri, defaultSurya);
  }

  return matched;
}
